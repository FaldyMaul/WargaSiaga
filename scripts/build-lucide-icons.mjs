function readSvgBody(fileName) {
  const sourcePath = path.join(iconRoot, `${fileName}.svg`);
  if (!fs.existsSync(sourcePath)) throw new Error(`Lucide icon not found: ${sourcePath}`);
  const svg = fs.readFileSync(sourcePath, "utf8");
  const match = svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i);
  if (!match) throw new Error(`Invalid Lucide SVG: ${sourcePath}`);
  return match[1].trim().replace(/\s*\r?\n\s*/g, "");
}

const icons = Object.fromEntries(
  Object.entries(curatedIcons).map(([alias, fileName]) => [alias, readSvgBody(fileName)])
);

const output = `// Generated by scripts/build-lucide-icons.mjs from the local Lucide repository.\n`
  + `// Source: ../../lucide-main/lucide-main/icons · License: Lucide ISC (some Feather-derived icons MIT).\n`
  + `export const LUCIDE_SOURCE = "local-lucide";\n`
  + `export const LUCIDE_ICONS = Object.freeze(${JSON.stringify(icons, null, 2)});\n`;

fs.writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${Object.keys(icons).length} local Lucide icons at ${path.relative(projectRoot, outputPath)}.`);
